pub fn solar_to_lunar(y: i32, m: u32, d: u32) -> (i32, u32, u32, bool) {
    if !(1900..=2100).contains(&y) {
        return (y, m, d, false);
    }
    let jdn = crate::bazi_exact::to_julian_day(y, m, d, 12, 0, 0).round() as i64;
    let mut yr_idx = (y - 1900) as usize;
    if yr_idx > 0 && jdn < LUNAR_TABLE_1900_2100[yr_idx].0 {
        yr_idx -= 1;
    }
    let (first_jdn, leap_idx, mask, mo_cnt) = LUNAR_TABLE_1900_2100[yr_idx];
    let lunar_year = 1900 + yr_idx as i32;
    let mut cur_jdn = first_jdn;

    for i in 0..mo_cnt {
        let days = if (mask & (1 << i)) != 0 { 30 } else { 29 };
        if jdn < cur_jdn + days {
            let lunar_day = (jdn - cur_jdn + 1) as u32;
            let mut m_num = (i + 1) as u32;
            let mut is_leap = false;
            if leap_idx > 0 {
                if i == leap_idx {
                    m_num = leap_idx as u32; // 闰月序号与前一个月相同
                    is_leap = true;
                } else if i > leap_idx {
                    m_num = i as u32; // 后续月份减 1
                }
            }
            return (lunar_year, m_num, lunar_day, is_leap);
        }
        cur_jdn += days;
    }
    (lunar_year, 12, 30, false)
}
